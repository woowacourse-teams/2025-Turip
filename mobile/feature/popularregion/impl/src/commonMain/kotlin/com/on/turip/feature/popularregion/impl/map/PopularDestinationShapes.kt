    /** 지도에 그릴 수 있는 카테고리 이름. */
    val regionCategoryNames: Set<String> get() = DESTINATIONS.keys

    fun destinationOf(regionCategoryName: String): Destination? = DESTINATIONS[regionCategoryName]

    /**
     * [regionCategoryName] 의 외곽 링 목록. 지도에 놓을 경계가 없으면 빈 목록이다.
     *
     * 시도 하나가 통째로 그 지역이면 시도 경계를, 시군구면 여기 실린 경계를 돌려준다.
     */
    fun shapesOf(regionCategoryName: String): List<List<GeoPoint>> {
        val destination: Destination = DESTINATIONS[regionCategoryName] ?: return emptyList()
        destination.sidoAreaCode?.let { return KoreaRegionShapes.shapesOf(it) }
        return decoded[regionCategoryName].orEmpty()
    }

